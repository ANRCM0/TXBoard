#!/usr/bin/env python3
"""Generate transport validators/types and the image-local contract from one source."""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'contracts/core-api/operations.v1.json'


def js(value):
    return json.dumps(value, ensure_ascii=True, separators=(',', ':'))


def absolute_end_pattern(value):
    result, escaped, bracket = '', False, False
    for char in value:
        if escaped:
            result += char
            escaped = False
        elif char == '\\':
            result += char
            escaped = True
        elif char == '[':
            result += char
            bracket = True
        elif char == ']':
            result += char
            bracket = False
        else:
            result += '(?![\\s\\S])' if char == '$' and not bracket else char
    return result


def expression(schema, definitions):
    supported = {'$ref', 'anyOf', 'const', 'enum', 'type', 'properties', 'required',
                 'additionalProperties', 'items', 'maxItems', 'minItems', 'maxLength',
                 'minLength', 'pattern', 'minimum', 'maximum', 'x-decimal-maximum'}
    unknown = set(schema) - supported
    if unknown:
        raise ValueError(f'Unsupported schema keywords: {unknown}')
    if '$ref' in schema:
        prefix = '#/definitions/'
        if not schema['$ref'].startswith(prefix):
            raise ValueError('Only local definition references are supported')
        return expression(definitions[schema['$ref'][len(prefix):]], definitions)
    if 'anyOf' in schema:
        return 'z.union([' + ','.join(expression(s, definitions) for s in schema['anyOf']) + '])'
    if 'const' in schema:
        return 'z.literal(' + js(schema['const']) + ')'
    if 'enum' in schema:
        if schema.get('type') != 'string':
            raise ValueError('String enum schemas require type: string for PHP/TypeScript parity')
        return 'z.enum(' + js(schema['enum']) + ')'
    kind = schema['type']
    if kind == 'object':
        if schema.get('additionalProperties') is not False:
            raise ValueError('Object schemas must be closed')
        required = schema.get('required', [])
        fields = [js(k) + ':' + expression(s, definitions) + ('' if k in required else '.optional()')
                  for k, s in schema['properties'].items()]
        result = 'z.strictObject({' + ','.join(fields) + '})'
    elif kind == 'array':
        result = 'z.array(' + expression(schema['items'], definitions) + ')'
    elif kind == 'integer':
        # JS transport numbers must remain exactly representable, including timestamps.
        result = 'z.number().int().safe()'
    elif kind in {'string', 'boolean', 'null'}:
        result = 'z.' + kind + '()'
    else:
        raise ValueError(f'Unsupported schema type: {kind}')
    for bound, method in [('minItems', 'min'), ('maxItems', 'max'), ('minLength', 'min'),
                          ('maxLength', 'max'), ('minimum', 'min'), ('maximum', 'max')]:
        if bound in schema:
            value = schema[bound]
            if kind == 'string':
                operator = '>=' if bound == 'minLength' else '<='
                result += '.refine(value => [...value].length ' + operator + ' ' + str(value) + ')'
                continue
            if kind == 'integer':
                value = min(value, 9007199254740991)
            result += f'.{method}({value})'
    if 'pattern' in schema:
        result += '.regex(new RegExp(' + js(absolute_end_pattern(schema['pattern'])) + ', "u"))'
    if 'x-decimal-maximum' in schema:
        value = schema['x-decimal-maximum']
        result += '.refine(value => /^(?:0|[1-9][0-9]*)(?![\\s\\S])/u.test(value) && (value.length < ' + str(len(value)) + ' || value.length === ' + str(len(value)) + ' && value <= ' + js(value) + '))'
    return result


def generated_types(contract):
    definitions = contract['definitions']
    lines = ["// Generated by scripts/generate-core-contracts.py; edit contracts/core-api/operations.v1.json.",
             "import { z } from 'zod'", '',
             'export const CORE_SURFACE_OPERATION_LIMIT = ' + str(surface_limit(contract)) + ' as const', '',
             'export const coreOperations = {']
    for name, spec in contract['operations'].items():
        lines.append('  ' + js(name) + ': { input: ' + expression(spec['input'], definitions)
                     + ', output: ' + expression(spec['output'], definitions)
                     + ', meta: ' + expression(spec.get('meta', {'type': 'object', 'properties': {}, 'required': [], 'additionalProperties': False}), definitions)
                     + ', domains: ' + js(spec['domains']) + ', permission: ' + js(spec['permission'])
                     + ', actor: ' + js(spec['actor']) + ', idempotency: ' + js(spec['idempotency']) + ' },')
    lines += ['} as const', '', 'export type CoreOperation = keyof typeof coreOperations',
              "export type CoreInput<K extends CoreOperation> = z.input<(typeof coreOperations)[K]['input']>",
              "export type CoreOutput<K extends CoreOperation> = z.output<(typeof coreOperations)[K]['output']>", '']
    lines += ["export type CoreMeta<K extends CoreOperation> = z.output<(typeof coreOperations)[K]['meta']>", '']
    return '\n'.join(lines)


def surface_limit(contract):
    limit = contract['limits']['surface_operations']
    if type(limit) is not int or not 1 <= limit <= 256:
        raise ValueError('Invalid reviewed surface operation bound')
    return limit


def generated_admin_surface(contract):
    ids = contract['surfaces']['admin']
    if len(ids) != len(set(ids)) or len(ids) > surface_limit(contract):
        raise ValueError('Invalid administrator surface')
    for name in ids:
        if name not in contract['operations'] or 'admin' not in contract['operations'][name]['domains']:
            raise ValueError('Administrator surface includes an invalid operation: ' + name)
    reads = [name for name in ids if contract['operations'][name]['idempotency'] == 'read']
    writes = [name for name in ids if contract['operations'][name]['idempotency'] != 'read'
              and contract['operations'][name]['actor'] != 'anonymous']
    lines = ['// Generated by scripts/generate-core-contracts.py; reviewed surface, never inferred from domains.',
             'export const CORE_ADMIN_OPERATIONS = ' + js(ids) + ' as const',
             'export const CORE_ADMIN_READ_OPERATIONS = ' + js(reads) + ' as const',
             'export const CORE_ADMIN_WRITE_OPERATIONS = ' + js(writes) + ' as const',
             'export type CoreAdminOperation = (typeof CORE_ADMIN_OPERATIONS)[number]',
             'export type CoreAdminReadOperation = (typeof CORE_ADMIN_READ_OPERATIONS)[number]',
             'export type CoreAdminWriteOperation = (typeof CORE_ADMIN_WRITE_OPERATIONS)[number]', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    contract = json.loads(SOURCE.read_text(encoding='utf-8'))
    bindings_path = ROOT / 'contracts/core-api/admin-bindings.v1.json'
    bindings = json.loads(bindings_path.read_text(encoding='utf-8'))
    for name, binding in bindings['bindings'].items():
        if not re.fullmatch(r'[A-Za-z][A-Za-z0-9]*Controller', binding['controller']) or not re.fullmatch(r'[a-z][A-Za-z0-9]*', binding['method']):
            raise ValueError('Invalid administrator target: ' + name)
        if name not in contract['surfaces']['admin'] or contract['operations'][name]['domains'] != ['admin']:
            raise ValueError('Binding must belong to the reviewed admin surface: ' + name)
        controller = ROOT / 'api/app/Http/Controllers/Txapi/Admin' / (binding['controller'] + '.php')
        if not controller.is_file() or 'public function ' + binding['method'] + '(' not in controller.read_text(encoding='utf-8'):
            raise ValueError('Unknown administrator binding: ' + name)
        if binding['payload'] is not None and binding['payload'] not in contract['operations'][name]['input']['properties']:
            raise ValueError('Unknown administrator payload: ' + name)
    types = generated_types(contract)
    surface = generated_admin_surface(contract)
    outputs = {
        ROOT / 'api/resources/contracts/core-operations.v1.json': SOURCE.read_text(encoding='utf-8'),
        ROOT / 'gateway/apps/gateway/src/contracts/core.generated.ts': types,
        ROOT / 'gateway/packages/core-sdk/src/contracts.generated.ts': types,
        ROOT / 'api/resources/contracts/admin-bindings.v1.json': bindings_path.read_text(encoding='utf-8'),
        ROOT / 'gateway/apps/gateway/src/contracts/core-admin.generated.ts': surface,
        ROOT / 'gateway/packages/core-sdk/src/admin.generated.ts': surface,
    }
    stale = []
    for path, content in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')
    if stale:
        raise SystemExit('Stale generated contracts: ' + ', '.join(stale))
    print(f"Core contracts: {len(contract['operations'])} operations; generated PHP resource and TypeScript validators/types are current.")


if __name__ == '__main__':
    main()
